#!/usr/bin/env python3
"""Generate the host OCaml build graph using ocamldep."""

import argparse
from graphlib import TopologicalSorter
from pathlib import Path
import subprocess


PACKAGE_MODULES = {
    "Sha256", "Ocpkg_format", "Pkg_archive", "Pkg_vendor", "Pkg_project",
    "Http_fetch", "Digest_index", "Build_cache", "Pkg_toolchain",
    "Pkg_compile", "Workspace",
}

TEST_ARGS = {
    "driver_test": ["$builddir/qbe/qbe", "$builddir/stdlib.sources"],
    "mutrec_closure_tail_test": ["$builddir/qbe/qbe"],
    "phi_split_test": ["$builddir/qbe/qbe"],
    "ocpkg_format_test": ["packages/snapshots/default.snap"],
}


def module_name(path):
    return path.stem[0].upper() + path.stem[1:]


def scan_dependencies(ocamldep, sources):
    output = subprocess.check_output(
        [ocamldep, "-modules", "-one-line", *map(str, sources)], text=True
    )
    return {
        Path(path): modules.split()
        for line in output.splitlines()
        for path, modules in [line.split(":", 1)]
    }


def write_if_changed(path, contents):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text() == contents:
        return
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(contents)
    temporary.replace(path)


def build_graph(library, binaries, tests, dependencies):
    lines = ["# Generated by tools/host-ninja.py. Edit the source or generator.", ""]

    def edge(output, rule, inputs, *, implicit=(), outputs=(), **variables):
        if outputs:
            output += " | " + " ".join(outputs)
        inputs = " ".join(map(str, inputs))
        if implicit:
            inputs += " | " + " ".join(implicit)
        lines.append(f"build {output}: {rule} {inputs}".rstrip())
        lines.extend(f"  {key} = {value}" for key, value in variables.items() if value)

    # A deleted source must trigger graph regeneration before Ninja checks its consumers.
    for sources in (library, binaries, tests):
        files = [str(path) for path in sources if path.parts[0] != "$host"]
        if files:
            edge(" $\n    ".join(files), "phony", [])
    lines.append("")

    implementations = {
        module_name(path): path for path in library if path.suffix == ".ml"
    }
    interfaces = {
        module_name(path): path for path in library if path.suffix == ".mli"
    }
    roots = {
        module_name(path): f"$host/lib/{path.stem}" for path in library
    }

    def unit(path, base, visible, interface=None):
        deps = []
        for name in dependencies[path]:
            if name in visible:
                deps.append(visible[name] + ".cmi")
            if path.suffix == ".ml" and name in implementations:
                deps.append(roots[name] + ".cmx")
        if path.suffix == ".mli":
            edge(base + ".cmi", "host_compile", [path], implicit=sorted(set(deps)))
        else:
            outputs = [base + ".o"]
            if interface is None:
                outputs.append(base + ".cmi")
            else:
                deps.append(base + ".cmi")
            edge(base + ".cmx", "host_compile", [path], implicit=sorted(set(deps)), outputs=outputs)

    edge("$host/generated/bigarray_header.ml", "host_header",
         ["runtime/ocamlcc_bigarray_types.h"])
    edge("$host/generated/ocpkg_version.ml", "host_version", ["ocamlcc.opam"])
    for path in library:
        name = module_name(path)
        unit(path, roots[name], roots, interfaces.get(name))

    for archive, modules in [
        ("ocamlcc", implementations.keys() - PACKAGE_MODULES),
        ("ocpkg", implementations.keys() & PACKAGE_MODULES),
    ]:
        graph = {
            name: sorted(set(dependencies[implementations[name]]) & modules)
            for name in sorted(modules)
        }
        order = TopologicalSorter(graph).static_order()
        edge(f"$host/{archive}.cmxa", "host_archive", [roots[name] + ".cmx" for name in order],
             outputs=[f"$host/{archive}.a"])

    for path in binaries:
        visible = {**roots, "Ocpkg_version": "$host/bin/ocpkg_version"}
        unit(path, f"$host/bin/{path.stem}", visible)
    edge("$host/digest_stat.o", "host_c", ["lib/digest_stat.c"])
    edge("$host/ocpkg_curl.o", "host_c", ["bin/ocpkg_curl.c"])
    edge("$host/curl-link.args", "host_curl_link_args", ["tools/curl-link-flags.sh"])

    compiler = ["$host/ocamlcc.cmxa"]
    package = ["$host/ocpkg.cmxa", "$host/digest_stat.o"]
    edge("$builddir/bin/occ", "host_link", compiler + ["$host/bin/main.cmx"],
         implicit=["$host/ocamlcc.a"])
    edge("$builddir/bin/ocpkg", "host_link",
         compiler + package + ["$host/bin/ocpkg_version.cmx", "$host/bin/ocpkg_main.cmx", "$host/ocpkg_curl.o"],
         implicit=["$host/ocamlcc.a", "$host/ocpkg.a", "$host/curl-link.args"],
         link_args="-args $host/curl-link.args")

    test_targets = []
    for path in tests:
        base = f"$host/test/{path.stem}"
        unit(path, base, roots)
        archives = list(compiler)
        archive_objects = ["$host/ocamlcc.a"]
        if set(dependencies[path]) & PACKAGE_MODULES:
            archives.extend(package)
            archive_objects.append("$host/ocpkg.a")
        executable = base + ".exe"
        edge(executable, "host_link", archives + [base + ".cmx"], implicit=archive_objects)
        args = TEST_ARGS.get(path.stem, [])
        expected = path.with_suffix(".expected")
        target = f"test_host_{path.stem}"
        if expected.is_file():
            edge(target, "host_golden_test", [executable], implicit=[*args, str(expected)],
                 args=" ".join(args), expected=str(expected))
        else:
            edge(target, "host_test", [executable], implicit=args, args=" ".join(args))
        test_targets.append(target)
    edge("test_host", "phony", test_targets)
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    parser.add_argument("--depfile", type=Path, required=True)
    parser.add_argument("--ocamldep", default="ocamldep")
    args = parser.parse_args()

    library = sorted([*Path("lib").glob("*.ml"), *Path("lib").glob("*.mli")])
    binaries = [Path("bin/main.ml"), Path("bin/ocpkg_main.ml")]
    tests = sorted(Path("test").glob("*_test.ml"))
    sources = library + binaries + tests
    dependencies = scan_dependencies(args.ocamldep, sources)
    header = Path("$host/generated/bigarray_header.ml")
    version = Path("$host/generated/ocpkg_version.ml")
    dependencies[header] = dependencies[version] = []
    graph = build_graph(library + [header], binaries + [version], tests, dependencies)
    write_if_changed(args.output, graph)
    # Use the absolute directory path to distinguish it from the phony test target.
    test_dir = str(Path("test").absolute()).replace("$", "$$").replace("#", "\\#").replace(" ", "\\ ")
    inputs = " ".join([test_dir, *map(str, sources)])
    write_if_changed(args.depfile, f"{args.output}: {inputs}\n")


if __name__ == "__main__":
    main()
