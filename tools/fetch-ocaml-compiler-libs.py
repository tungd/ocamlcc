def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        while True:
            chunk = f.read(1 << 20)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()


def verify_sha256(path: Path) -> None:
    actual = sha256_file(path)
    if actual != TARBALL_SHA256:
        raise RuntimeError(
            f"SHA-256 mismatch for {path}: got {actual}, expected {TARBALL_SHA256}"
        )


def resolve_tarball(explicit: Path | None, cache_dir: Path) -> Path:
    if explicit is not None:
        if not explicit.is_file():
            raise RuntimeError(f"tarball not found: {explicit}")
        verify_sha256(explicit)
        return explicit

    cached = cache_dir / f"ocaml-{OCAML_VERSION}.tar.gz"
    if cached.is_file():
        verify_sha256(cached)
        return cached

    # Reuse opam's local download cache when available (still SHA-256 verified).
    opam_root = Path(os.environ.get("OPAMROOT", Path.home() / ".opam"))
    opam_cached = (
        opam_root / "download-cache" / "sha256" / TARBALL_SHA256[:2] / TARBALL_SHA256
    )
    if opam_cached.is_file():
        verify_sha256(opam_cached)
        return opam_cached

    cache_dir.mkdir(parents=True, exist_ok=True)
    tmp = cached.with_suffix(".tar.gz.part")
    print(f"Downloading {TARBALL_URL} -> {cached} ...", file=sys.stderr)
    try:
        with urllib.request.urlopen(TARBALL_URL, timeout=120) as resp, tmp.open("wb") as out:
            shutil.copyfileobj(resp, out)
        verify_sha256(tmp)
        tmp.replace(cached)
    except Exception:
        if tmp.exists():
            tmp.unlink()
        raise
    return cached


def read_member(tf: tarfile.TarFile, member_name: str) -> bytes:
    f = tf.extractfile(member_name)
    if f is None:
        raise RuntimeError(f"missing member in tarball: {member_name}")
    return f.read()


def find_member(names: set[str], basename: str) -> str:
    for d in SEARCH_DIRS:
        cand = f"{TARBALL_PREFIX}/{d}/{basename}"
        if cand in names:
            return cand
    raise RuntimeError(f"could not locate {basename} in {SEARCH_DIRS}")


def generate_config_ml(tf: tarfile.TarFile) -> bytes:
    fixed = read_member(tf, f"{TARBALL_PREFIX}/utils/config.fixed.ml").decode("utf-8")
    common = read_member(tf, f"{TARBALL_PREFIX}/utils/config.common.ml.in").decode("utf-8")
    for placeholder, value in MAGIC_NUMBERS.items():
        common = common.replace(placeholder, value)
    if "@" in common:
        # Check specifically for leftover @VAR@ placeholders.
        import re
        leftover = re.findall(r"@[A-Za-z0-9_]+@", common)
        if leftover:
            raise RuntimeError(f"unsubstituted placeholders in config.common.ml.in: {leftover}")
    return (fixed + "\n" + common).encode("utf-8")


def generate_lexer_ml(tf: tarfile.TarFile, dest: Path) -> None:
    mll_bytes = read_member(tf, f"{TARBALL_PREFIX}/parsing/lexer.mll")
    ocamllex = shutil.which("ocamllex")
    if ocamllex is None:
        raise RuntimeError("ocamllex not found on PATH (needed to generate lexer.ml from lexer.mll)")
    with tempfile.TemporaryDirectory(prefix="ocamlcc_lexer_") as tmp:
        mll_path = Path(tmp) / "lexer.mll"
        mll_path.write_bytes(mll_bytes)
        res = subprocess.run(
            [ocamllex, "-q", "-o", str(dest), str(mll_path)],
            capture_output=True,
            text=True,
        )
        if res.returncode != 0:
            raise RuntimeError(f"ocamllex failed: {res.stdout}{res.stderr}")


def extract_sources(tarball: Path, out_dir: Path) -> dict:
    staging = out_dir.parent / (out_dir.name + ".tmp")
    if staging.exists():
        shutil.rmtree(staging)
    comp_dir = staging / "compiler-libs"
    comp_dir.mkdir(parents=True, exist_ok=True)

    with tarfile.open(tarball, "r:gz") as tf:
        names = set(tf.getnames())

        for mod in COMPILER_LIBS_MODULES:
            base = mod[0].lower() + mod[1:]
            if mod == "Config":
                (comp_dir / "config.mli").write_bytes(
                    read_member(tf, f"{TARBALL_PREFIX}/utils/config.mli")
                )
                (comp_dir / "config.ml").write_bytes(generate_config_ml(tf))
            elif mod == "CamlinternalMenhirLib":
                (comp_dir / "camlinternalMenhirLib.mli").write_bytes(
                    read_member(tf, f"{TARBALL_PREFIX}/boot/menhir/menhirLib.mli")
                )
                (comp_dir / "camlinternalMenhirLib.ml").write_bytes(
                    read_member(tf, f"{TARBALL_PREFIX}/boot/menhir/menhirLib.ml")
                )
            elif mod == "Parser":
                (comp_dir / "parser.mli").write_bytes(
                    read_member(tf, f"{TARBALL_PREFIX}/boot/menhir/parser.mli")
                )
                (comp_dir / "parser.ml").write_bytes(
                    read_member(tf, f"{TARBALL_PREFIX}/boot/menhir/parser.ml")
                )
            elif mod == "Lexer":
                (comp_dir / "lexer.mli").write_bytes(
                    read_member(tf, f"{TARBALL_PREFIX}/parsing/lexer.mli")
                )
                generate_lexer_ml(tf, comp_dir / "lexer.ml")
            else:
                mli_member = find_member(names, f"{base}.mli")
                ml_member = find_member(names, f"{base}.ml")
                (comp_dir / f"{base}.mli").write_bytes(read_member(tf, mli_member))
                (comp_dir / f"{base}.ml").write_bytes(read_member(tf, ml_member))

        for mod in MLI_ONLY_MODULES:
            base = mod[0].lower() + mod[1:]
            mli_member = find_member(names, f"{base}.mli")
            (comp_dir / f"{base}.mli").write_bytes(read_member(tf, mli_member))

    manifest = {
        "version": OCAML_VERSION,
        "url": TARBALL_URL,
        "sha256": TARBALL_SHA256,
        "tarball": str(tarball),
        "modules": COMPILER_LIBS_MODULES,
        "mli_only": MLI_ONLY_MODULES,
    }
    (staging / "MANIFEST.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
    )

    if out_dir.exists():
        shutil.rmtree(out_dir)
    staging.replace(out_dir)
    return manifest


def main() -> int:
    root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(
        description="Fetch and extract pinned OCaml 5.5.0 compiler-libs.common subset."
    )
    parser.add_argument(
        "--tarball",
        type=Path,
        default=None,
        help="Path to a pre-downloaded ocaml-5.5.0.tar.gz (verified against pinned SHA-256).",
    )
    parser.add_argument(
        "--cache-dir",
        type=Path,
        default=root / "build" / "bootstrap" / "cache",
        help="Cache directory for downloaded tarball.",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=root / "build" / "bootstrap" / "src",
        help="Output directory for extracted compiler-libs sources and MANIFEST.json.",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Re-extract even if MANIFEST.json already matches the pinned SHA-256.",
    )
    args = parser.parse_args()

    manifest_path = args.out / "MANIFEST.json"
    if not args.force and manifest_path.is_file():
        try:
            existing = json.loads(manifest_path.read_text(encoding="utf-8"))
            if (
                existing.get("version") == OCAML_VERSION
                and existing.get("sha256") == TARBALL_SHA256
                and len(existing.get("modules", [])) == len(COMPILER_LIBS_MODULES)
            ):
                print(
                    f"compiler-libs {OCAML_VERSION} already extracted at {args.out} "
                    f"({len(COMPILER_LIBS_MODULES)} modules, sha256 verified)."
                )
                return 0
        except Exception:
            pass

    try:
        tarball = resolve_tarball(args.tarball, args.cache_dir)
        manifest = extract_sources(tarball, args.out)
    except Exception as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    print(
        f"Extracted OCaml {manifest['version']} compiler-libs subset -> {args.out} "
        f"({len(manifest['modules'])} .ml/.mli + {len(manifest['mli_only'])} .mli-only, "
        f"sha256={manifest['sha256'][:12]}...)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
