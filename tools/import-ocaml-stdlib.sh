#!/usr/bin/env bash
set -euo pipefail

# Import/vendor upstream OCaml Stdlib sources and lib-* tests into
# vendor/ocaml-stdlib/ in a reproducible, pinned way.

DEFAULT_VERSION="5.5.0"
DEFAULT_COMMIT="f5238509da6029a44ba0eb648f5dff7d9c89f519"
REPO_URL="https://github.com/ocaml/ocaml.git"

VERSION="$DEFAULT_VERSION"
EXPECTED_COMMIT="$DEFAULT_COMMIT"
FROM_GIT=""
OUT_DIR="vendor/ocaml-stdlib"

usage() {
  cat <<'EOF'
usage: tools/import-ocaml-stdlib.sh [options]
  --version VER     Upstream OCaml tag/version (default: 5.5.0)
  --commit SHA      Expected git commit SHA (verified when set; default pinned for 5.5.0)
  --from-git DIR    Reuse an existing local git checkout of ocaml/ocaml
  --out DIR         Destination directory (default: vendor/ocaml-stdlib)
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    --version)
      VERSION="$2"
      if [ "$VERSION" != "$DEFAULT_VERSION" ]; then
        EXPECTED_COMMIT=""
      fi
      shift 2
      ;;
    --commit)
      EXPECTED_COMMIT="$2"
      shift 2
      ;;
    --from-git)
      FROM_GIT="$2"
      shift 2
      ;;
    --out)
      OUT_DIR="$2"
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "unknown option: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
case "$OUT_DIR" in
  /*) ;;
  *) OUT_DIR="$ROOT_DIR/$OUT_DIR" ;;
esac

TMP_DIR=""
cleanup() {
  if [ -n "$TMP_DIR" ] && [ -d "$TMP_DIR" ]; then
    rm -rf "$TMP_DIR"
  fi
}
trap cleanup EXIT

if [ -n "$FROM_GIT" ]; then
  SRC_GIT="$FROM_GIT"
else
  TMP_DIR="$(mktemp -d "${TMPDIR:-/tmp}/ocamlcc_vendor.XXXXXX")"
  SRC_GIT="$TMP_DIR/ocaml-src"
  git clone --depth 1 --filter=blob:none --sparse --branch "$VERSION" "$REPO_URL" "$SRC_GIT"
  git -C "$SRC_GIT" sparse-checkout set stdlib testsuite/tests
fi

ACTUAL_COMMIT="$(git -C "$SRC_GIT" rev-parse HEAD)"
if [ -n "$EXPECTED_COMMIT" ] && [ "$ACTUAL_COMMIT" != "$EXPECTED_COMMIT" ]; then
  echo "error: commit mismatch for $VERSION: got $ACTUAL_COMMIT, expected $EXPECTED_COMMIT" >&2
  exit 1
fi

if [ ! -f "$SRC_GIT/stdlib/StdlibModules" ] || [ ! -d "$SRC_GIT/testsuite/tests" ]; then
  echo "error: $SRC_GIT does not contain stdlib/ and testsuite/tests/" >&2
  exit 1
fi

rm -rf "$OUT_DIR"
mkdir -p "$OUT_DIR/src" "$OUT_DIR/testsuite/tests"

# Copy stdlib sources, interfaces, and build metadata.
cp "$SRC_GIT/stdlib/"*.ml "$OUT_DIR/src/"
cp "$SRC_GIT/stdlib/"*.mli "$OUT_DIR/src/"
for f in .depend StdlibModules Compflags expand_module_aliases.awk remove_module_aliases.awk sys.ml.in META.in; do
  if [ -f "$SRC_GIT/stdlib/$f" ]; then
    cp "$SRC_GIT/stdlib/$f" "$OUT_DIR/src/"
  fi
done
if [ -f "$SRC_GIT/LICENSE" ]; then
  cp "$SRC_GIT/LICENSE" "$OUT_DIR/LICENSE"
fi

# Generate sys.ml from sys.ml.in matching the pinned OCaml release.
IFS='.' read -r VER_MAJOR VER_MINOR VER_REST <<EOF
$VERSION
EOF
VER_PATCH="${VER_REST%%[^0-9]*}"
VER_PATCH="${VER_PATCH:-0}"

sed \
  -e "s|@configure_input@|Generated by tools/import-ocaml-stdlib.sh from sys.ml.in|g" \
  -e "s|@VERSION@|$VERSION|g" \
  -e "s|@OCAML_DEVELOPMENT_VERSION@|false|g" \
  -e "s|@OCAML_VERSION_MAJOR@|$VER_MAJOR|g" \
  -e "s|@OCAML_VERSION_MINOR@|$VER_MINOR|g" \
  -e "s|@OCAML_VERSION_PATCHLEVEL@|$VER_PATCH|g" \
  -e "s|@OCAML_RELEASE_EXTRA@|None|g" \
  "$OUT_DIR/src/sys.ml.in" > "$OUT_DIR/src/sys.ml"

# Copy upstream stdlib test suites (lib-*), excluding non-stdlib otherlibs.
TEST_COUNT=0
for d in "$SRC_GIT/testsuite/tests"/lib-*; do
  [ -d "$d" ] || continue
  base="$(basename "$d")"
  case "$base" in
    lib-dynlink-*|lib-runtime-events|lib-str|lib-systhreads|lib-threads|lib-unix)
      continue
      ;;
  esac
  cp -R "$d" "$OUT_DIR/testsuite/tests/$base"
  TEST_COUNT=$((TEST_COUNT + 1))
done

ML_COUNT="$(find "$OUT_DIR/src" -maxdepth 1 -name '*.ml' | wc -l | tr -d ' ')"
MLI_COUNT="$(find "$OUT_DIR/src" -maxdepth 1 -name '*.mli' | wc -l | tr -d ' ')"

cat > "$OUT_DIR/UPSTREAM.txt" <<EOF
upstream: $REPO_URL
version: $VERSION
commit: $ACTUAL_COMMIT
ml_files: $ML_COUNT
mli_files: $MLI_COUNT
lib_test_suites: $TEST_COUNT
EOF

echo "Imported OCaml $VERSION ($ACTUAL_COMMIT) -> $OUT_DIR ($ML_COUNT .ml, $MLI_COUNT .mli, $TEST_COUNT lib-* suites)"
