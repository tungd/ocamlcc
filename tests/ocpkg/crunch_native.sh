#!/bin/sh
set -eu
timeout_cmd=$(command -v timeout || command -v gtimeout)

runner=$1
case "$runner" in /*) ;; *) runner="$PWD/$runner";; esac
mkdir -p "$2"
cd "$2"
work="$PWD"
export OCPKG_CACHE="${OCPKG_CACHE:-$work/cache}"
export SOURCE_DATE_EPOCH=0 TERM=dumb LC_ALL=C
mkdir -p "$work/logs"
receipt="$work/receipt.txt"
: > "$receipt"

run() {
    job=$1
    expected=$2
    shift 2
    log="$work/logs/$job.log"
    start=$(date +%s)
    status=0
    "$timeout_cmd" 180 "$@" > "$log" 2>&1 || status=$?
    printf 'command %s exit=%s expected=%s seconds=%s log=%s\n' \
        "$job" "$status" "$expected" "$(( $(date +%s) - start ))" "$log" >> "$receipt"
    if [ "$status" -ne "$expected" ]; then
        printf '%s: exit %s, expected %s\n' "$job" "$status" "$expected" >&2
        tail -30 "$log" >&2
        exit 1
    fi
}

check() {
    check_name=$1
    shift
    if "$@"; then
        printf 'PASS %s\n' "$check_name" | tee -a "$receipt"
    else
        printf 'FAIL %s\n' "$check_name" | tee -a "$receipt" >&2
        exit 1
    fi
}

cat > ocpkg.mod <<'MOD'
module crunch
kind exe
snapshot default
require (
  crunch 4.1.0
)
MOD

run tidy 0 "$runner" tidy
run vendor 0 "$runner" vendor
run build 0 "$runner" build -v -o "$work/ocaml-crunch"
binary="$work/ocaml-crunch"
upstream="$work/vendor/crunch/test"
run version 0 "$binary" --version
check version test "$(cat "$work/logs/version.log")" = 'v4.1.0'
run help 0 "$binary" --help=plain
check help grep -q 'DIRECTORIES' "$work/logs/help.log"
run invalid-option 124 "$binary" --not-an-option

mkdir -p "$work/fixtures"
cd "$work/fixtures"
run plain 0 "$binary" --mode=plain -o t1_plain.ml "$upstream/t1"
check plain cmp -s t1_plain.ml "$upstream/t1_plain.expected.ml"
run extension 0 "$binary" --mode=plain -e ext -o t1_plain_ext.ml "$upstream/t1"
check extension cmp -s t1_plain_ext.ml "$upstream/t1_plain_ext.expected.ml"
run lwt 0 "$binary" --mode=lwt -o t1.ml "$upstream/t1"
check lwt-code cmp -s t1.ml "$upstream/t1.expected.ml"
check lwt-interface cmp -s t1.mli "$upstream/t1.expected.mli"

mkdir -p "$work/roundtrip/src" "$work/roundtrip/data/nested"
cd "$work/roundtrip"
: > data/empty
awk 'BEGIN {for (row=0; row<33; row++) for (n=0; n<256; n++) printf "%c", n}' > data/nested/all-bytes.bin
printf 'hello\000world\n"\\' > 'data/quotes".txt'
awk 'BEGIN {for (n=0; n<3000; n++) printf "abcd"}' > data/repeated

cat > ocpkg.mod <<'MOD'
module roundtrip
kind exe
entry src/main.ml
source src
snapshot default
MOD
cat > src/main.ml <<'ML'
let check name size hash =
  assert (Embedded.size name = Some size);
  assert (Embedded.hash name = Some hash);
  let contents = In_channel.with_open_bin ("data/" ^ name) In_channel.input_all in
  assert (Embedded.read name = Some contents)

let () =
  check "empty" 0 "d41d8cd98f00b204e9800998ecf8427e";
  check "nested/all-bytes.bin" 8448 "6258b144ba26646616065bca291c9746";
  check "quotes\".txt" 14 "ff67fd129cbab951f8b5ca414597440a";
  check "repeated" 12000 "40f91677e2bbf91b7da6e67dc8850842";
  assert (Embedded.read "missing" = None);
  print_endline "roundtrip: ok"
ML
run roundtrip-tidy 0 "$runner" tidy
for block in 0 17; do
    run "roundtrip-generate-$block" 0 "$binary" --mode=plain --silent -b "$block" -o src/embedded.ml data
    run "roundtrip-build-$block" 0 "$runner" build -o "consumer-$block"
    run "roundtrip-run-$block" 0 "./consumer-$block"
    check "roundtrip-$block" test "$(cat "$work/logs/roundtrip-run-$block.log")" = 'roundtrip: ok'
done
run live-clock 0 env -u SOURCE_DATE_EPOCH "$binary" --mode=plain --silent -o live.ml data
check live-clock grep -q '^(\* Generated by: ocaml-crunch' live.ml
printf 'status=passed checks=9 receipt=%s\n' "$receipt" | tee -a "$receipt"
